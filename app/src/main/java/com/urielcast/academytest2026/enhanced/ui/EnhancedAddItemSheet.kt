import com.urielcast.academytest2026.R

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun EnhancedAddItemSheet(
    onDismiss: () -> Unit,
    onSave: (String) -> Unit,
) {
    val sheetState = rememberModalBottomSheetState()
    ModalBottomSheet(onDismissRequest = onDismiss, sheetState = sheetState) {
        var name by remember { mutableStateOf("") }
        val focusRequester = remember { FocusRequester() }

        fun save() {
            if (name.isNotBlank()) onSave(name.trim())
        }

        Column(
            modifier = Modifier
                .fillMaxWidth()
                .imePadding()
                .padding(horizontal = 24.dp)
                .padding(bottom = 24.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp),
        ) {
            Text(
                text = stringResource(R.string.enh_new_item),
                style = MaterialTheme.typography.titleLarge,
            )

            OutlinedTextField(
                value = name,
                onValueChange = { name = it },
                label = { Text(stringResource(R.string.enh_name)) },
                singleLine = true,
                keyboardOptions = KeyboardOptions(
                    capitalization = KeyboardCapitalization.Sentences,
                    imeAction = ImeAction.Done,
                ),
                keyboardActions = KeyboardActions(onDone = { save() }),
                modifier = Modifier
                    .fillMaxWidth()
                    .focusRequester(focusRequester),
            )

            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.End,
                verticalAlignment = Alignment.CenterVertically,
            ) {
                TextButton(onClick = onDismiss) { Text(stringResource(R.string.enh_cancel)) }
                Button(onClick = { save() }, enabled = name.isNotBlank()) {
                    Text(stringResource(R.string.enh_save))
                }
            }
        }

        LaunchedEffect(Unit) { focusRequester.requestFocus() }
    }
}
